    /// <summary>Returns safe SVG inner markup for a Lucide name, alias, or legacy value.</summary>
    public static string Resolve(string? name)
    {
        if (string.IsNullOrWhiteSpace(name)) return Icons["circle"];

        var key = name.Trim().Replace("\uFE0F", string.Empty).Replace("\u200D", string.Empty);
        if (Icons.TryGetValue(key, out var markup)) return markup;
        if (Aliases.TryGetValue(key, out var alias) && Icons.TryGetValue(alias, out var aliasMarkup)) return aliasMarkup;
        if (Legacy.TryGetValue(key, out var legacyName) && Icons.TryGetValue(legacyName, out var legacyMarkup)) return legacyMarkup;
        return Icons["circle"];
    }
